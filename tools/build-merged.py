FAMILY = "Muteshebbek"

DEFAULT_MERGE = {
    "min_size_px": 7,
    "max_size_px": 100,
    "native_beats_scaled": True,
    "upscale_scope": "winners",
    "filler": {"enabled": True, "scope": "both", "font": "cozette-vector"},
    "max_strikes": 0,
    "max_output_mb": 0,
    "priority": [],
    "size_select": {},
}


def load_merge_config(path):
    """Read merge.json over the built-in defaults and validate it."""
    cfg = json.loads(json.dumps(DEFAULT_MERGE))  # deep copy
    if path:
        with open(path, encoding="utf-8") as f:
            raw = json.load(f)
        for key in DEFAULT_MERGE:
            if key in raw:
                if key == "filler":
                    cfg["filler"].update(raw["filler"] or {})
                else:
                    cfg[key] = raw[key]
    if not isinstance(cfg["priority"], list) or not all(
            isinstance(p, str) for p in cfg["priority"]):
        print("ERROR: merge priority must be a list of package names",
              file=sys.stderr)
        sys.exit(1)
    lo, hi = cfg["min_size_px"], cfg["max_size_px"]
    if not (isinstance(lo, int) and isinstance(hi, int) and 1 <= lo < hi):
        print("ERROR: merge min_size_px/max_size_px invalid", file=sys.stderr)
        sys.exit(1)
    if not isinstance(cfg["native_beats_scaled"], bool):
        print("ERROR: merge native_beats_scaled must be a boolean",
              file=sys.stderr)
        sys.exit(1)
    if cfg["upscale_scope"] not in ("all", "winners"):
        print("ERROR: merge upscale_scope must be 'all' or 'winners'",
              file=sys.stderr)
        sys.exit(1)
    if cfg["filler"].get("scope") not in ("both", "otb", "ttf"):
        print("ERROR: merge filler.scope must be both/otb/ttf",
              file=sys.stderr)
        sys.exit(1)
    for key in ("max_strikes", "max_output_mb"):
        if not isinstance(cfg[key], int) or cfg[key] < 0:
            print(f"ERROR: merge {key} must be an int >= 0", file=sys.stderr)
            sys.exit(1)
    sel = cfg["size_select"]
    if not isinstance(sel, dict) or any(
            not isinstance(pkg, str)
            or not isinstance(sizes, list)
            or not sizes
            or not all(isinstance(s, int) and not isinstance(s, bool) and s > 0
                       for s in sizes)
            for pkg, sizes in sel.items()):
        print("ERROR: merge size_select must be {package: [px, ...]}",
              file=sys.stderr)
        sys.exit(1)
    return cfg


def regular_score(entry):
    """Lower = more regular. Excludes icon variants (returns None)."""
    name = entry["path"].lower()
    if "icons" in name:
        return None
    score = 0
    if entry.get("format") == "pcf":
        score += 5  # BDF preferred, PCF is lossy fallback
    xlfd = (entry.get("xlfd") or "").split("-")
    weight = xlfd[3].lower() if len(xlfd) > 4 else ""
    slant = xlfd[4].lower() if len(xlfd) > 5 else ""
    if weight in ("bold", "black", "demi", "demibold", "heavy"):
        score += 10
    if slant in ("i", "o") or "italic" in name or "oblique" in name:
        score += 10
    if "bold" in name or re.search(r"(^|[-_.])b\.", name):
        score += 10
    if re.search(r"(^|[-_.])(r|n|regular|normal|medium|roman)\.", name):
        score -= 1
    return score


def strike_metrics(entry, px):
    """(ascent, descent) for one strike, descent positive.

    fonttosfnt stamps every strike with the global max (e.g. 52/-12 from
    a 64px strike), which makes small sizes space lines far too wide.
    Prefer the source header values (sizes.json: BDF FONT_ASCENT/DESCENT,
    PCF accelerators), then the BDF bounding box, then a px-proportional
    split as last resort.
    """
    asc, desc = entry.get("ascent"), entry.get("descent")
    if (isinstance(asc, int) and isinstance(desc, int)
            and asc > 0 and desc >= 0 and asc + desc <= 2 * px + 4):
        return asc, desc
    bb = entry.get("bbox")
    if (isinstance(bb, list) and len(bb) == 4
            and all(isinstance(v, int) for v in bb)):
        a, d = bb[1] + bb[3], -bb[3]
        if a > 0 and d >= 0 and a + d <= 2 * px + 4:
            return a, d
    a = max(1, round(px * 0.8))
    return a, px - a


def scale_hex_row(hexstr, orig_width, factor):
    """Scale one BDF bitmap row x factor, kept byte-aligned hex.

    orig_width is the UNscaled glyph width: complete rows already span
    the full byte width, so padding must use this basis (padding to the
    scaled width would prepend a zero byte and shift all ink right).
    """
    # Defensive: rows may omit leading zero nibbles; pad those back.
    hexstr = hexstr.strip().zfill(2 * ((orig_width + 7) // 8))
    val = int(hexstr or "0", 16)
    total = len(hexstr) * 4
    out = []
    for i in range(orig_width):
        out.extend([(val >> (total - 1 - i)) & 1] * factor)
    while len(out) % 8:
        out.append(0)
    num = 0
    for b in out:
        num = (num << 1) | b
    return format(num, "X").zfill(len(out) // 4)


def scale_xlfd(line, factor):
    """Scale pixel/point/avgwidth fields of an XLFD font name line."""
    parts = line.split("-")
    if len(parts) == 15:
        try:
            parts[7] = str(int(parts[7]) * factor)
            parts[8] = str(int(parts[8]) * factor)
            parts[12] = str(int(parts[12]) * factor)
            return "-".join(parts)
        except ValueError:
            pass
    return line


def scale_bdf_text(text, factor):
    """Pixel-double BDF source text by an integer factor (metrics + ink)."""
    out = []
    in_bitmap = False
    cur_w = None
    for raw in text.splitlines():
        line = raw
        if in_bitmap:
            if line == "ENDCHAR":
                in_bitmap = False
                out.append("ENDCHAR")
                continue
            out.extend([scale_hex_row(line, cur_w // factor, factor)] * factor
                       if cur_w else [line])
            continue
        if line.startswith("SIZE ") and len(line.split()) >= 4:
            p = line.split()
            out.append(f"SIZE {int(p[1]) * factor} {p[2]} {p[3]}")
        elif line.startswith("FONTBOUNDINGBOX ") and len(line.split()) >= 5:
            v = [int(x) * factor for x in line.split()[1:5]]
            out.append("FONTBOUNDINGBOX " + " ".join(map(str, v)))
        elif line.startswith("FONT_ASCENT ") and len(line.split()) >= 2:
            out.append(f"FONT_ASCENT {int(line.split()[1]) * factor}")
        elif line.startswith("FONT_DESCENT ") and len(line.split()) >= 2:
            out.append(f"FONT_DESCENT {int(line.split()[1]) * factor}")
        elif line.startswith("PIXEL_SIZE ") and len(line.split()) >= 2:
            out.append(f"PIXEL_SIZE {int(line.split()[1]) * factor}")
        elif line.startswith("POINT_SIZE ") and len(line.split()) >= 2:
            out.append(f"POINT_SIZE {int(line.split()[1]) * factor}")
        elif line.startswith("AVERAGE_WIDTH ") and len(line.split()) >= 2:
            out.append(f"AVERAGE_WIDTH {int(line.split()[1]) * factor}")
        elif line.startswith("FONT "):
            out.append(scale_xlfd(line, factor))
        elif line.startswith("SWIDTH ") and len(line.split()) >= 3:
            p = line.split()
            out.append(f"SWIDTH {int(p[1]) * factor} {int(p[2]) * factor}")
        elif line.startswith("DWIDTH ") and len(line.split()) >= 3:
            p = line.split()
            out.append(f"DWIDTH {int(p[1]) * factor} {int(p[2]) * factor}")
        elif line.startswith("BBX ") and len(line.split()) >= 5:
            v = [int(x) * factor for x in line.split()[1:5]]
            cur_w = v[0]
            out.append("BBX " + " ".join(map(str, v)))
        elif line == "BITMAP":
            in_bitmap = True
            out.append("BITMAP")
        else:
            out.append(raw)
    return "\n".join(out) + "\n"


def parse_bdf_bitmaps(text):
    """BDF text -> {encoding: (bbx, hex_rows)} for encoded glyphs.

    bbx is the BDF BBX (width, height, xoff, yoff); yoff is the bottom
    edge of the bitmap relative to the baseline (negative = descends).
    rows are top-to-bottom hex strings, left-padded has needed.
    """
    glyphs = {}
    enc = bbx = rows = None
    in_bitmap = False
    for line in text.splitlines():
        if line.startswith("STARTCHAR "):
            enc = bbx = rows = None
            in_bitmap = False
        elif line.startswith("ENCODING "):
            parts = line.split()
            if enc is None:  # first ENCODING line is the primary one
                try:
                    enc = int(parts[1])
                except (IndexError, ValueError):
                    enc = None
        elif line.startswith("BBX "):
            parts = line.split()
            if len(parts) >= 5:
                try:
                    bbx = tuple(int(v) for v in parts[1:5])
                except ValueError:
                    bbx = None
        elif line == "BITMAP":
            rows = []
            in_bitmap = True
        elif line == "ENDCHAR":
            in_bitmap = False
            if enc is not None and enc >= 0 and bbx and rows is not None:
                glyphs[enc] = (bbx, rows)
            enc = bbx = rows = None
        elif in_bitmap:
            rows.append(line.strip())
    return glyphs


def outline_glyph(bbx, rows, scale):
    """Trace one bitmap glyph into a TrueType glyph.

    Each horizontal run of set pixels becomes one rectangle contour.
    Every contour is wound the same way, so nonzero fill gives the union
    of the ink and leaves counters (holes) empty. scale maps one source
    pixel to font units (unitsPerEm / strike pixel size).
    """
    from fontTools.pens.ttGlyphPen import TTGlyphPen

    w, h, xoff, yoff = bbx
    pen = TTGlyphPen(None)
    nbytes = (w + 7) // 8
    if nbytes == 0:
        return pen.glyph()
    total = nbytes * 8
    blank = "0" * (nbytes * 2)
    for ry in range(h):
        hexrow = (rows[ry].zfill(nbytes * 2)
                  if ry < len(rows) else blank)
        try:
            val = int(hexrow, 16)
        except ValueError:
            continue
        x = 0
        while x < w:
            if not ((val >> (total - 1 - x)) & 1):
                x += 1
                continue
            x0 = x
            while x < w and ((val >> (total - 1 - x)) & 1):
                x += 1
            x0u = round((xoff + x0) * scale)
            x1u = round((xoff + x) * scale)
            y0u = round((yoff + h - ry - 1) * scale)
            y1u = round((yoff + h - ry) * scale)
            pen.moveTo((x0u, y0u))
            pen.lineTo((x1u, y0u))
            pen.lineTo((x1u, y1u))
            pen.lineTo((x0u, y1u))
            pen.closePath()
    return pen.glyph()


def strike_bdf_text(strike, pkgmap):
    """BDF source text for one selected strike (PCF converted on demand)."""
    full = strike.get("fullpath") or ""
    if full.endswith(".bdf"):
        with open(full, encoding="ascii", errors="replace") as f:
            return f.read()
    entry = strike.get("_entry")
    if entry is None:
        raise RuntimeError("no BDF source for this strike")
    return bdf_source_text(entry, pkgmap)


def add_ttf_outlines(font, strikes, pkgmap):
    """Fill the blank glyf table from the bitmap strikes (largest wins).

    Returns how many glyphs got real outlines. Glyphs absent from every
    strike stay blank (they have no ink anyway). Filler strikes marked
    "traceable": False (scope "otb") are skipped.
    """
    upem = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyf = font["glyf"]
    done = set()
    by_px = {}
    for s in strikes:
        if s.get("traceable", True):
            by_px.setdefault(s["px"], []).append(s)
    for px in sorted(by_px, reverse=True):
        text = strike_bdf_text(by_px[px][0], pkgmap)
        scale = upem / px
        for enc, (bbx, rows) in parse_bdf_bitmaps(text).items():
            name = cmap.get(enc)
            if name is None or name in done:
                continue
            glyf[name] = outline_glyph(bbx, rows, scale)
            done.add(name)
    if hasattr(font["maxp"], "recalc"):
        # maxp.recalc reads each glyph's bbox; fonttosfnt leaves them lazy,
        # so materialise the bounds first (composites included).
        for name in font.getGlyphOrder():
            g = glyf[name]
            if g.numberOfContours:
                g.recalcBounds(glyf)
        font["maxp"].recalc(font)
    return len(done)


def add_filler_outlines(font, ttf_path):
    """Scale the filler TTF's outlines into blank glyf slots (scope "ttf").

    Only glyphs that no bitmap strike covered stay blank, so this is usually
    a no-op; it keeps the TTF complete when the OTB got no filler strike.
    """
    from fontTools.ttLib import TTFont
    from fontTools.misc.transform import Transform
    from fontTools.pens.transformPen import TransformPen
    from fontTools.pens.ttGlyphPen import TTGlyphPen

    src = TTFont(ttf_path)
    try:
        src_cmap = src.getBestCmap()
        src_glyphset = src.getGlyphSet()
        scale = font["head"].unitsPerEm / src["head"].unitsPerEm
        glyf = font["glyf"]
        filled = 0
        for code, name in font.getBestCmap().items():
            if glyf[name].numberOfContours:
                continue
            sname = src_cmap.get(code)
            if sname is None:
                continue
            pen = TTGlyphPen(None)
            src_glyphset[sname].draw(
                TransformPen(pen, Transform(scale, 0, 0, scale, 0, 0)))
            glyph = pen.glyph()
            if glyph.numberOfContours:
                glyf[name] = glyph
                filled += 1
        if filled and hasattr(font["maxp"], "recalc"):
            for name in font.getGlyphOrder():
                g = glyf[name]
                if g.numberOfContours:
                    g.recalcBounds(glyf)
            font["maxp"].recalc(font)
        return filled
    finally:
        src.close()


def bdf_source_text(entry, pkgmap):
    """Raw BDF text for a sizes.json entry (PCF converted via freetype)."""
    full = os.path.join(pkgmap[entry["_pkg"]], "share", "fonts", entry["path"])
    if entry.get("format") == "bdf":
        with open(full, encoding="ascii", errors="replace") as f:
            return f.read()
    if pcf2bdf is None:
        raise RuntimeError("pcf2bdf unavailable (freetype-py missing?)")
    with tempfile.NamedTemporaryFile(suffix=".bdf", delete=False) as tmp:
        tmppath = tmp.name
    try:
        pcf2bdf.convert(full, tmppath)
        with open(tmppath, encoding="ascii", errors="replace") as f:
            return f.read()
    finally:
        try:
            os.unlink(tmppath)
        except OSError:
            pass


# ------------------------------------------------------- selection plan ---
def build_native_index(files):
    """(pkg, px) -> [entries] for BDF/PCF files, plus per-pkg native sizes."""
    by_pkg_px = {}
    for e in files:
        if e.get("format") in ("bdf", "pcf") and isinstance(e.get("pixel_size"), int):
            by_pkg_px.setdefault((e["package"], e["pixel_size"]), []).append(e)
    native_sizes = {}
    for (pkg, px), entries in by_pkg_px.items():
        if any(regular_score(e) is not None for e in entries):
            native_sizes.setdefault(pkg, set()).add(px)
    return by_pkg_px, {p: sorted(v) for p, v in native_sizes.items()}


def make_best_native(by_pkg_px):
    """Pick the most regular BDF/PCF entry for one (package, px)."""
    def best_native(pkg, px):
        cands = []
        for e in by_pkg_px.get((pkg, px), []):
            s = regular_score(e)
            if s is not None:
                cands.append((s, e["path"], e))
        if not cands:
            return None
        cands.sort(key=lambda t: (t[0], t[1]))
        return cands[0][2]
    return best_native


def compute_native_winners(winners, best_native, merge):
    """Highest-priority font with a real BDF/PCF at each target px."""
    native_win = {}
    for px in range(merge["min_size_px"], merge["max_size_px"] + 1):
        w = winners.get(str(px))
        if not w:
            continue
        for contender in w["contenders"]:
            if best_native(contender, px) is not None:
                native_win[px] = contender
                break
    return native_win


def build_plan(winners, priority, native_sizes, best_native, selected, merge,
               native_win):
    """Ordered candidate list per target px (best first), before materializing.

    This is the cheap pre-priority pass: only (package, source px, factor)
    tuples are compared, nothing is read or written, and every px ends up
    with at most one winner. Losers stay attached for the verbose report.
    """
    rank = {name: i for i, name in enumerate(priority)}
    max_rank = len(rank)
    lo, hi = merge["min_size_px"], merge["max_size_px"]
    plan = {}
    for px in range(lo, hi + 1):
        cands = []
        contender = native_win.get(px)
        if contender is not None:
            cands.append({"kind": "native", "package": contender,
                          "src_px": px, "factor": 1,
                          "entry": best_native(contender, px)})
        for pkg in selected:
            for src in native_sizes.get(pkg, ()):
                if src >= px or px % src:
                    continue
                factor = px // src
                if factor < 2:
                    continue
                e = best_native(pkg, src)
                if e is None:
                    continue
                cands.append({"kind": "scaled", "package": pkg,
                              "src_px": src, "factor": factor, "entry": e})
        # One descriptor per package: prefer the smallest factor (least
        # pixelation) when a font reaches the same px from several sizes.
        best = {}
        for c in cands:
            prev = best.get(c["package"])
            if prev is None or c["factor"] < prev["factor"]:
                best[c["package"]] = c
        cands = list(best.values())

        def order_key(c):
            cat = 0
            if merge["native_beats_scaled"] and c["kind"] != "native":
                cat = 1
            return (cat, rank.get(c["package"], max_rank), c["factor"],
                    c["package"])

        cands.sort(key=order_key)
        for i, c in enumerate(cands):
            c["rank"] = rank.get(c["package"], max_rank)
            c["winner"] = i == 0
        plan[px] = cands
    return plan


def estimate_plan(plan, merge, filler_active, filler_glyphs):
    """Cheap upper-bound-ish byte estimate for the pre-write overflow guard."""
    total = 0
    for px, cands in plan.items():
        if cands:
            c = cands[0]
            bb = c["entry"].get("bbox")
            glyphs = c["entry"].get("glyphs") or 0
            if isinstance(bb, list) and len(bb) == 4:
                w, h = bb[0] * c["factor"], bb[1] * c["factor"]
            else:
                w, h = px, px
        elif filler_active:
            w, h = max(1, round(px * 6 / 13)), px
            glyphs = filler_glyphs or 0
        else:
            continue
        total += glyphs * (((int(w) + 7) // 8) * int(h) + 8)
    return total


def precheck_plan(plan, merge, filler_active, filler_glyphs):
    """Pre-priority overflow check: fail before anything is written."""
    targets = len(plan)
    reached = sum(1 for c in plan.values() if c)
    gaps = targets - reached
    strikes = reached + (gaps if filler_active else 0)
    est = estimate_plan(plan, merge, filler_active, filler_glyphs)
    print(f"precheck: {targets} target sizes, {reached} reachable by bitmap "
          f"fonts, {gaps} filler gaps, {strikes} strikes total, "
          f"est. bitmap payload <= {est / 1e6:.1f} MB")
    if merge["max_strikes"] and strikes > merge["max_strikes"]:
        print(f"ERROR: precheck would write {strikes} strikes > "
              f"max_strikes={merge['max_strikes']}", file=sys.stderr)
        sys.exit(1)
    if merge["max_output_mb"] and est > merge["max_output_mb"] * 1e6:
        print(f"ERROR: precheck estimated {est / 1e6:.1f} MB > "
              f"max_output_mb={merge['max_output_mb']}", file=sys.stderr)
        sys.exit(1)
    return strikes, est


# --------------------------------------------------------- verbose output ---
def print_verbose(strikes, winners, rank, merge, filler_name, installed):
    """Verbose merged-font report, including every priority duel."""
    lo, hi = merge["min_size_px"], merge["max_size_px"]
    print(f"\n== {FAMILY} merge: {lo}-{hi}px ==")
    print(f"   native_beats_scaled={merge['native_beats_scaled']}  "
          f"upscale_scope={merge['upscale_scope']}  "
          f"filler={filler_name or 'off'} (scope={merge['filler']['scope']})")
    print(f"{'px':>4}  {'winner':<16} {'kind':<8} {'scale':<15} "
          f"{'rank':>4}  file")
    for s in strikes:
        if s["kind"] == "native":
            scale, cat = "native", "native"
        elif s["kind"] == "scaled":
            scale, cat = f"{s['scale']}x of {s['source_px']}px", "scaled"
        else:
            scale, cat = f"@ {s['px']}px", "filler"
        rank_s = "-" if s["kind"] == "filler" else str(s.get("priority_rank"))
        print(f"{s['px']:4d}  {s['package']:<16} {cat:<8} {scale:<15} "
              f"{rank_s:>4}  {s.get('file', '')}")
    actual = {s["px"]: s["package"] for s in strikes}
    # Contenders come from winners.json (declared, priority-ordered) so the
    # duels stay visible even though only the winners are built/installed.
    duels = {int(px): w["contenders"] for px, w in winners.items()
             if isinstance(w, dict) and len(w.get("contenders", [])) > 1}
    if duels:
        print("\n-- priority decisions (declared contenders in priority order) --")
        for px in sorted(duels):
            conts = duels[px]
            win = actual.get(px, conts[0])
            note = "" if win in installed else " [filler]"
            print(f"{px:>4}px: {win} wins (priority #{rank.get(win, len(rank))}){note}")
            for c in conts:
                mark = "WIN " if c == win else "    "
                tag = "" if c in installed else "  (not installed)"
                print(f"        {mark}{c:<16} priority #{rank.get(c, len(rank))}{tag}")
    n_kind = {"native": 0, "scaled": 0, "filler": 0}
    for s in strikes:
        n_kind[s["kind"]] += 1
    print(f"\nsummary: {len(strikes)} strikes = {n_kind['native']} native + "
          f"{n_kind['scaled']} scaled + {n_kind['filler']} filler")
    by_font = {}
    for s in strikes:
        by_font[s["package"]] = by_font.get(s["package"], 0) + 1
    print("won sizes per font: " + ", ".join(
        f"{p}x{n}" for p, n in sorted(by_font.items(), key=lambda kv: -kv[1])))


HEX_DIGITS = set("0123456789abcdefABCDEF")


def bdf_has_ink(text):
    """True if a BDF has at least one set bitmap pixel.

    Bitmap rows are the only lines that are nothing but hex digits, so a
    non-zero such line proves the strike has ink. A conversion that lost
    every glyph (e.g. proggyfonts' WebbyCaps) would otherwise be blank.
    """
    for line in text.splitlines():
        s = line.strip()
        if s and all(c in HEX_DIGITS for c in s) and int(s, 16):
            return True
    return False


def materialize_scaled(pkg, src_px, entry, factor, pkgmap, tmpdir):
    """Write a pixel-doubled BDF for one scaled candidate; return its path."""
    text = bdf_source_text(entry, pkgmap)
    if not bdf_has_ink(text):
        raise RuntimeError("source has no ink after conversion")
    path = os.path.join(tmpdir, f"{pkg}-{src_px}px-x{factor}.bdf")
    with open(path, "w", encoding="ascii") as f:
        f.write(scale_bdf_text(text, factor))
    return path


def materialize_filler(ttf_path, px, family, tmpdir):
    """Rasterize the filler TTF at one ppem; return (path, ascent, descent)."""
    if ttf2bdf is None:
        raise RuntimeError("ttf2bdf unavailable (freetype-py missing?)")
    text, asc, desc = ttf2bdf.rasterize(ttf_path, px, family=family)
    path = os.path.join(tmpdir, f"filler-{px}px.bdf")
    with open(path, "w", encoding="ascii") as f:
        f.write(text)
    return path, asc, desc


def materialize_pcf_bdf(entry, pkgmap, tmpdir, cache):
    """Convert a native PCF to BDF for fonttosfnt (once per source file).

    fonttosfnt reads PCF directly, but some PCFs (profont) carry full-cell
    blank bitmaps that it turns into corrupt EBDT entries FreeType rejects.
    Going through the (blank-glyph aware) converter avoids that and keeps
    native and scaled strikes byte-identical in style.
    """
    key = (entry["_pkg"], entry["path"])
    if key in cache:
        return cache[key]
    text = bdf_source_text(entry, pkgmap)
    if not bdf_has_ink(text):
        # Conversion lost the glyphs (non-Unicode charmap); fonttosfnt
        # handles the raw PCF better than an empty BDF. Cache the None so
        # the caller keeps using the original file.
        cache[key] = None
        return None
    name = entry["path"].replace("/", "_").rsplit(".", 2)[0]
    path = os.path.join(tmpdir, f"{entry['_pkg']}-{name}.bdf")
    with open(path, "w", encoding="ascii") as f:
        f.write(text)
    cache[key] = path
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pkgmap", required=False, default=None)
    ap.add_argument("--sizes", required=True)
    ap.add_argument("--winners", required=True)
    ap.add_argument("--force", nargs="*", default=[], metavar="PKG",
                    help="packages to upscale even without a native win")
    ap.add_argument("--merge", required=False, default=None)
    ap.add_argument("--filler-ttf", dest="filler_ttf", required=False,
                    default=None, help="TTF rasterized for filler strikes")
    ap.add_argument("--out", required=False, default=None)
    ap.add_argument("--report", required=False, default=None)
    ap.add_argument("--out-ttf", dest="out_ttf", required=False, default=None,
                    help="also write an outline .ttf (for apps without "
                         "bitmap-strike/OTB support)")
    ap.add_argument("--dry-run", action="store_true",
                    help="print the strike plan without running fonttosfnt")
    ap.add_argument("--quiet", action="store_true",
                    help="suppress the verbose strike plan")
    args = ap.parse_args()

    if args.dry_run:
        if args.out or args.report or args.pkgmap:
            print("dry-run: ignoring --out/--report/--pkgmap "
                  "(nothing is written)", file=sys.stderr)
    elif not args.pkgmap or not args.out or not args.report:
        ap.error("--pkgmap/--out/--report are required without --dry-run")

    merge = load_merge_config(args.merge)
    filler_on = bool(merge["filler"]["enabled"])
    filler_scope = merge["filler"]["scope"]
    filler_family = merge["filler"].get("font", "cozette-vector")
    if filler_on and (filler_scope in ("both", "otb") or args.out_ttf) \
            and not args.filler_ttf and not args.dry_run:
        print("ERROR: filler is enabled but --filler-ttf was not given",
              file=sys.stderr)
        sys.exit(1)

    pkgmap = {}
    if args.pkgmap:
        with open(args.pkgmap, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    store_path, _, logical = line.rpartition(" ")
                    pkgmap[logical] = store_path
    with open(args.sizes, encoding="utf-8") as f:
        files = json.load(f)["files"]
    with open(args.winners, encoding="utf-8") as f:
        winners = json.load(f)["winners"]
    # Priority lives in merge.json now (written by flake.nix); --force only
    # names extra packages to upscale beyond the native winners.
    priority = merge.get("priority") or []
    rank = {name: i for i, name in enumerate(priority)}
    forced = set(args.force)

    for e in files:
        e["_pkg"] = e["package"]
    by_pkg_px, native_sizes = build_native_index(files)
    # size_select restricts a font's native sizes for the merge: it can win
    # natively and be upscaled only from these px; all other real sizes of
    # the font stay out of the merged result.
    for pkg, sizes in (merge.get("size_select") or {}).items():
        real = native_sizes.get(pkg, [])
        missing = sorted(set(sizes) - set(real))
        if missing:
            print(f"WARN: size_select {pkg}: no native {missing} "
                  f"(real: {real})", file=sys.stderr)
        if pkg in native_sizes:
            native_sizes[pkg] = sorted(set(sizes) & set(real))
    best_native = make_best_native(by_pkg_px)

    # Which fonts get upscaled? Winners are always selected; "all" selects
    # every font with a usable BDF/PCF, plus anything force-declared.
    native_win = compute_native_winners(winners, best_native, merge)
    selected = set(native_win.values())
    if merge["upscale_scope"] == "all":
        selected |= set(native_sizes)
    selected |= {pkg for pkg in forced if pkg in native_sizes}
    plan = build_plan(winners, priority, native_sizes, best_native,
                      selected, merge, native_win)

    filler_glyphs = None
    if filler_on:
        try:
            from fontTools.ttLib import TTFont
            if args.filler_ttf:
                fsrc = TTFont(args.filler_ttf, lazy=True)
                try:
                    filler_glyphs = fsrc["maxp"].numGlyphs
                finally:
                    fsrc.close()
        except Exception:  # noqa: BLE001 - estimate only
            filler_glyphs = None

    filler_active = filler_on and filler_scope in ("both", "otb")
    n_strikes, est = precheck_plan(plan, merge, filler_active, filler_glyphs)

    tmpdir = None
    strikes = []
    skipped = []
    bdf_cache = {}
    if not args.dry_run:
        tmpdir = tempfile.mkdtemp(prefix="muteshebbek-scale-")
    for px in sorted(plan):
        cands = plan[px]
        picked = None
        for c in cands:
            if c["kind"] == "native":
                e = c["entry"]
                asc, desc = strike_metrics(e, px)
                full = os.path.join(pkgmap[c["package"]], "share", "fonts",
                                    e["path"]) if pkgmap else ""
                if e["format"] == "pcf" and not args.dry_run \
                        and (e["path"].endswith(".pcf")
                             or e["path"].endswith(".pcf.gz")):
                    alt = materialize_pcf_bdf(e, pkgmap, tmpdir, bdf_cache)
                    if alt is not None:
                        full = alt
                picked = {"px": px, "package": c["package"], "file": e["path"],
                          "format": e["format"], "sha256": e["sha256"],
                          "ascent": asc, "descent": desc, "scale": 1,
                          "source_px": px, "fullpath": full, "_entry": e,
                          "kind": "native", "priority_rank": c["rank"],
                          "traceable": True}
                break
            if args.dry_run:
                asc, desc = strike_metrics(c["entry"], c["src_px"])
                picked = {"px": px, "package": c["package"],
                          "file": c["entry"]["path"],
                          "format": c["entry"]["format"],
                          "sha256": c["entry"]["sha256"],
                          "ascent": asc * c["factor"],
                          "descent": desc * c["factor"], "scale": c["factor"],
                          "source_px": c["src_px"], "fullpath": "",
                          "_entry": c["entry"], "kind": "scaled",
                          "priority_rank": c["rank"], "traceable": True}
                break
            try:
                path = materialize_scaled(c["package"], c["src_px"], c["entry"],
                                          c["factor"], pkgmap, tmpdir)
            except Exception as exc:  # noqa: BLE001 - fall through
                print(f"WARN: cannot scale {c['package']} {c['src_px']}px "
                      f"x{c['factor']} for {px}px ({exc}), trying next",
                      file=sys.stderr)
                continue
            asc, desc = strike_metrics(c["entry"], c["src_px"])
            picked = {"px": px, "package": c["package"],
                      "file": c["entry"]["path"],
                      "format": c["entry"]["format"],
                      "sha256": c["entry"]["sha256"],
                      "ascent": asc * c["factor"],
                      "descent": desc * c["factor"], "scale": c["factor"],
                      "source_px": c["src_px"], "fullpath": path,
                      "_entry": c["entry"], "kind": "scaled",
                      "priority_rank": c["rank"], "traceable": True}
            break
        if picked is None and filler_active:
            if args.dry_run:
                picked = {"px": px, "package": filler_family,
                          "file": filler_family, "format": "ttf-raster",
                          "sha256": "", "ascent": max(1, round(px * 0.8)),
                          "descent": px - max(1, round(px * 0.8)), "scale": 1,
                          "source_px": px, "fullpath": "", "_entry": None,
                          "kind": "filler", "priority_rank": None,
                          "traceable": True}
            else:
                try:
                    path, asc, desc = materialize_filler(
                        args.filler_ttf, px, filler_family, tmpdir)
                    picked = {"px": px, "package": filler_family,
                              "file": os.path.basename(args.filler_ttf),
                              "format": "ttf-raster",
                              "sha256": "", "ascent": asc, "descent": desc,
                              "scale": 1, "source_px": px, "fullpath": path,
                              "_entry": None, "kind": "filler",
                              "priority_rank": None,
                              "traceable": filler_scope == "both"}
                except Exception as exc:  # noqa: BLE001 - gap stays a gap
                    print(f"WARN: filler rasterization failed for {px}px "
                          f"({exc})", file=sys.stderr)
        if picked is None:
            gaps = ",".join(c["package"] for c in cands) or "none"
            skipped.append({"px": px, "contenders": gaps,
                            "reason": "no BDF/PCF (native or scaled) and "
                                      "filler off/failed"})
            print(f"WARN: no strike for {px}px, skipped", file=sys.stderr)
            continue
        picked["contenders"] = [
            {"package": c["package"], "kind": c["kind"], "src_px": c["src_px"],
             "factor": c["factor"], "rank": c["rank"],
             "winner": c is cands[0]} for c in cands]
        strikes.append(picked)

    if not strikes:
        print("ERROR: nothing selected", file=sys.stderr)
        sys.exit(1)

    if not args.quiet:
        installed = {e["package"] for e in files}
        print_verbose(strikes, winners, rank, merge,
                      filler_family if filler_on else None, installed)

    if args.dry_run:
        print(f"dry-run: {len(strikes)} strikes, {len(skipped)} skipped "
              f"(nothing written)")
        return 0

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    inputs = [s["fullpath"] for s in strikes]
    r = subprocess.run(["fonttosfnt", "-o", args.out] + inputs,
                       capture_output=True, text=True)
    print(r.stdout[-2000:] if r.stdout else "")
    if r.returncode != 0:
        print(r.stderr[-2000:], file=sys.stderr)
        sys.exit(1)

    from fontTools.ttLib import TTFont
    font = TTFont(args.out)
    outlined = filler_outlined = 0
    try:
        name = font["name"]
        for plat in ((3, 1, 0x409), (1, 0, 0)):
            name.setName(FAMILY, 1, *plat)
            name.setName(f"{FAMILY} Regular", 4, *plat)
            name.setName(f"{FAMILY}-Regular", 6, *plat)
            name.setName(FAMILY, 16, *plat)
        # Per-strike line metrics: fonttosfnt stamps every strike with the
        # global max ascender/descender, so small sizes inherit a huge line
        # height. Restore each strike's own values instead.
        want = {s["px"]: (s["ascent"], s["descent"]) for s in strikes}
        for tag in ("EBLC", "CBLC"):
            if tag not in font:
                continue
            for st in font[tag].strikes:
                px = st.bitmapSizeTable.ppemX
                if px not in want:
                    print(f"WARN: no metrics for {px}px strike, kept as-is",
                          file=sys.stderr)
                    continue
                asc, desc = want[px]
                st.bitmapSizeTable.hori.ascender = asc
                st.bitmapSizeTable.hori.descender = -desc
                st.bitmapSizeTable.vert.ascender = asc
                st.bitmapSizeTable.vert.descender = -desc
        # Global Win metrics must agree with hhea/typo (≈1em line) instead
        # of the head-bbox union (≈1.36em), or Win-metric apps add leading.
        os2 = font["OS/2"]
        os2.usWinAscent = max(0, font["hhea"].ascent)
        os2.usWinDescent = max(0, -font["hhea"].descent)
        font.save(args.out)
        if args.out_ttf:
            os.makedirs(os.path.dirname(os.path.abspath(args.out_ttf)),
                        exist_ok=True)
            outlined = add_ttf_outlines(font, strikes, pkgmap)
            if filler_on and filler_scope == "ttf" and args.filler_ttf:
                filler_outlined = add_filler_outlines(font, args.filler_ttf)
            font.save(args.out_ttf)
            print(f"outlined {outlined} glyphs"
                  + (f" (+{filler_outlined} filler outlines)"
                     if filler_outlined else "") + f" -> {args.out_ttf}")
    finally:
        font.close()

    report = {"font": os.path.basename(args.out), "family": FAMILY,
              "generated_by": "tools/build-merged.py via winners.json",
              "merge": {k: v for k, v in merge.items()},
              "strikes": [{k: s[k] for k in ("px", "package", "file", "format",
                                            "sha256", "ascent", "descent",
                                            "scale", "source_px", "kind",
                                            "priority_rank", "contenders")}
                          for s in strikes],
              "skipped": skipped}
    if args.out_ttf:
        report["ttf"] = {"file": os.path.basename(args.out_ttf),
                         "outlined_glyphs": outlined,
                         "filler_outlines": filler_outlined,
                         "outline_source": "largest bitmap strike per glyph"}
    with open(args.report, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=1, sort_keys=True)
        f.write("\n")
    print(f"merged {len(strikes)} strikes -> {args.out}")


if __name__ == "__main__":
    main()
