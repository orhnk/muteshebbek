#!/usr/bin/env python3
"""Build the merged font: one strike per px size, winner per priority.

Algorithm (configuration in merge.json, generated by flake.nix; see
load_merge_config):

1. Target sizes are every integer px from min_size_px to max_size_px (default
   7-100). The TTF/OTB therefore covers the whole range, not just the sizes a
   font happens to ship natively.

2. Candidate generation ("multiply selected fonts until they reach MAX"):
   * a native strike is a font that really has a BDF/PCF at exactly that px.
   * a scaled strike is a selected font's native px multiplied by an integer
     factor so the product lands on the target px (e.g. tamsyn 9px *3 = 27px).
   Every font that wins at least one size natively is "selected" and gets
   upscaled up to max_size_px (upscale_scope="winners"; "all" upscales every
   font). Packages named via --force are selected too.

3. Tie-break: with native_beats_scaled=true (default) each px prefers a native
   strike; only within the same category (native first, then scaled) does
   the priority list (merge.json) decide. With false, priority decides
   globally. Losers stay in the report so every duel is visible. size_select
   (merge.json, "font:size=9,12,13" in flake.nix) restricts a font to the
   listed sizes for both native wins and scaling sources.

4. Filler: px sizes no candidate reaches (e.g. 19px or 77px) are filled with a
   bitmap strike rasterized from a TTF (CozetteVector) by tools/ttf2bdf.py, so
   both OTB and TTF still display something at every size. filler.scope picks
   "both" (default), "otb" or "ttf".

Pre-priority overflow check: the selection pass only keeps lightweight
descriptors (package, source px, factor) and deduplicates to at most one
strike per px BEFORE anything is rasterized or written. max_strikes /
max_output_mb (both 0 = off) abort the build if the result would be
unreasonably large; nothing is written when the check fails.

Cross-application compatibility (--out-ttf): the OTB is an sfnt whose scalable
glyphs are blank, so apps that ignore embedded bitmap strikes (EBLC/EBDT)
render nothing. Given --out-ttf we additionally trace every covered glyph from
the largest bitmap strike that has it (one rectangle contour per horizontal
run of ink, nonzero winding) and fill it into the (blank) glyf table, then save
a plain .ttf. The bitmap strikes are kept, so bitmap-aware renderers still get
the pixel-perfect native size.

Usage:
  build-merged.py --pkgmap pkgmap.txt --sizes sizes.json \\
      --winners winners.json --merge merge.json --force pkg ... \\
      --filler-ttf CozetteVector.ttf \\
      --out Muteshebbek.otb --out-ttf Muteshebbek.ttf \\
      --report merged-report.json
  build-merged.py --dry-run --sizes sizes.json --winners winners.json \\
      --merge merge.json
      (prints the verbose strike plan, builds nothing)

winners.json and merge.json (which carries the priority list) are written
by flake.nix; the per-px winner is decided there from fonts.json + priority.
"""

